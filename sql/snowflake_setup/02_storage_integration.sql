-- AWS側IAMロール作成後に、個人の管理ユーザーで実行する。
-- 別環境ではAWSアカウント・ロールARN・バケット名を変更する。
-- CREATE OR REPLACEで既存Integrationを再生成しない。

USE ROLE ACCOUNTADMIN;

CREATE STORAGE INTEGRATION IF NOT EXISTS THELOOK_S3_INTEGRATION
    TYPE = EXTERNAL_STAGE
    STORAGE_PROVIDER = 'S3'
    ENABLED = TRUE
    STORAGE_AWS_ROLE_ARN =
      'arn:aws:iam::324475349753:role/TheLookSnowflakeReadRole'
    STORAGE_ALLOWED_LOCATIONS =
      ('s3://thelook-pipeline-keisuke-20261028/processed/');

GRANT OWNERSHIP ON INTEGRATION THELOOK_S3_INTEGRATION
    TO ROLE SYSADMIN COPY CURRENT GRANTS;

USE ROLE SYSADMIN;

GRANT USAGE ON INTEGRATION THELOOK_S3_INTEGRATION
    TO ROLE THELOOK_ETL_ROLE;

DESC INTEGRATION THELOOK_S3_INTEGRATION;

