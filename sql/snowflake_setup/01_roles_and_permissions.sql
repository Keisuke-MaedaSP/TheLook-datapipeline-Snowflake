-- 初回の管理用セットアップ。個人の管理ユーザーで実行する。
-- 作成時の利用者はKEIMAEDA。別の環境ではユーザー名を変更する。
-- IF NOT EXISTSは既存定義を変更しない。SHOW結果で設定を確認する。

-- Step 2：ロールの作成と管理階層。テーブル等への権限は別途付与する。
USE ROLE SECURITYADMIN;

CREATE ROLE IF NOT EXISTS THELOOK_ETL_ROLE
    COMMENT = 'TheLook pipeline loading and validation role';
CREATE ROLE IF NOT EXISTS THELOOK_ANALYST_ROLE
    COMMENT = 'TheLook analysis read role';

-- 右側のSYSADMINが、左側のロールの権限を継承する。
-- ETLと分析者のロール間には相互の継承を設定しない。
GRANT ROLE THELOOK_ETL_ROLE TO ROLE SYSADMIN;
GRANT ROLE THELOOK_ANALYST_ROLE TO ROLE SYSADMIN;

-- 付与先を確認する。
SHOW GRANTS OF ROLE THELOOK_ETL_ROLE;
SHOW GRANTS OF ROLE THELOOK_ANALYST_ROLE;

GRANT ROLE THELOOK_ETL_ROLE TO USER KEIMAEDA;
GRANT ROLE THELOOK_ANALYST_ROLE TO USER KEIMAEDA;

-- Step 2：専用の計算資源。既存COMPUTE_WHは変更しない。
USE ROLE SYSADMIN;

CREATE WAREHOUSE IF NOT EXISTS THELOOK_WH
    WAREHOUSE_TYPE = 'STANDARD'
    WAREHOUSE_SIZE = 'XSMALL'
    GENERATION = '2'
    AUTO_SUSPEND = 60
    AUTO_RESUME = TRUE
    INITIALLY_SUSPENDED = TRUE
    ENABLE_QUERY_ACCELERATION = FALSE
    COMMENT = 'TheLook learning pipeline compute';

-- Warehouse利用と、テーブルの読み書き権限は別に管理する。
GRANT USAGE ON WAREHOUSE THELOOK_WH TO ROLE THELOOK_ETL_ROLE;
GRANT USAGE ON WAREHOUSE THELOOK_WH TO ROLE THELOOK_ANALYST_ROLE;

SHOW WAREHOUSES LIKE 'THELOOK_WH';
SHOW GRANTS ON WAREHOUSE THELOOK_WH;

-- Step 2：保存先と、その範囲を利用する権限を設定する。
USE ROLE SYSADMIN;

CREATE DATABASE IF NOT EXISTS THELOOK_DB;
CREATE SCHEMA IF NOT EXISTS THELOOK_DB.STAGING;
CREATE SCHEMA IF NOT EXISTS THELOOK_DB.ANALYTICS;

GRANT USAGE ON DATABASE THELOOK_DB TO ROLE THELOOK_ETL_ROLE;
GRANT USAGE ON DATABASE THELOOK_DB TO ROLE THELOOK_ANALYST_ROLE;

GRANT USAGE ON SCHEMA THELOOK_DB.STAGING TO ROLE THELOOK_ETL_ROLE;
GRANT USAGE ON SCHEMA THELOOK_DB.ANALYTICS TO ROLE THELOOK_ANALYST_ROLE;

-- これらのUSAGEだけでは、テーブルをSELECT/INSERTする権限は付かない。
SHOW GRANTS TO ROLE THELOOK_ETL_ROLE;
SHOW GRANTS TO ROLE THELOOK_ANALYST_ROLE;

GRANT CREATE TABLE, CREATE FILE FORMAT, CREATE STAGE
    ON SCHEMA THELOOK_DB.STAGING
    TO ROLE THELOOK_ETL_ROLE;

-- ANALYTICSのデータ公開・SELECT権限は別途設計する。
-- 現在の分析ロールはDB/ANALYTICS/WHのUSAGEのみ。
