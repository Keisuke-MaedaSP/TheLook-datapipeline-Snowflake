-- 01の権限設定、02のStorage Integration、AWS側の信頼関係を設定した後に実行する。
-- 個人ユーザーからETLロールへ切り替えて作成する。

USE ROLE THELOOK_ETL_ROLE;
USE SECONDARY ROLES NONE;

CREATE FILE FORMAT IF NOT EXISTS THELOOK_DB.STAGING.THELOOK_PARQUET_FORMAT
    TYPE = PARQUET
    USE_LOGICAL_TYPE = TRUE;

-- 既存フォーマットにも、実際のロードで確認済みの日時解釈を反映する。
ALTER FILE FORMAT THELOOK_DB.STAGING.THELOOK_PARQUET_FORMAT
    SET USE_LOGICAL_TYPE = TRUE;

CREATE STAGE IF NOT EXISTS THELOOK_DB.STAGING.THELOOK_S3_STAGE
    URL = 's3://thelook-pipeline-keisuke-20261028/processed/'
    STORAGE_INTEGRATION = THELOOK_S3_INTEGRATION
    FILE_FORMAT = (
      FORMAT_NAME = 'THELOOK_DB.STAGING.THELOOK_PARQUET_FORMAT'
    );

LIST @THELOOK_DB.STAGING.THELOOK_S3_STAGE;
