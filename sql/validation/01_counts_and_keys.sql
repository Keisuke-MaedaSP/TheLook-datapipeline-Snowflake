-- SELECTによる確認SQL。NG行があってもSQL自体は正常終了する。
USE ROLE THELOOK_ETL_ROLE;
USE SECONDARY ROLES NONE;
USE WAREHOUSE THELOOK_WH;
USE DATABASE THELOOK_DB;
USE SCHEMA STAGING;

SELECT 'distribution_centers' AS TABLE_NAME, COUNT(*) AS ROW_COUNT,
       10 AS EXPECTED_ROWS, COUNT(*) = 10 AS COUNT_MATCHES,
       COUNT(*) - COUNT(id) AS KEY_NULLS,
       COUNT(id) - COUNT(DISTINCT id) AS DUPLICATE_EXTRA_ROWS
FROM distribution_centers
UNION ALL
